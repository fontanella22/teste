test('resumo: janela de 7 dias, previsões, pendências e dia de Brasília',()=>{
 assert.equal(digestDate(new Date('2026-10-14T01:00:00Z')),'2026-10-13');
 const farm=emptyFarm();farm.animals=[{id:'a',name:'Flor',tag:'01'}];
 farm.vaccines=[{id:'old',animal:'a',name:'Vacina A',date:'2025-01-01',next:'2025-07-01'},{id:'new',animal:'a',name:'Vacina A',date:'2026-01-01',next:'2026-10-20'}, {id:'far',animal:'a',name:'Vacina B',date:'2026-01-01',next:'2026-10-21'}];
 farm.reproduction=[{id:'r',animal:'a',type:'Inseminação',date:'2026-01-01',expected:'2026-10-19'}];
 const result=dailySummary(farm,'2026-10-13');assert.deepEqual(result.map(i=>i.id),['r-r','v-new']);assert.equal(result[1].distance,7);
 farm.reproduction[0].outcome='Não confirmada';assert.equal(dailySummary(farm,'2026-10-13').length,1);
});
